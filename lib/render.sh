# shellcheck shell=bash
# Generate llama-swap.yaml and the OpenCode config from the active profile.

LLAMA_SERVER_BIN() { echo "$ULA_OPT/llama.cpp/current/llama-server"; }
SWAP_YAML="$ULA_CONFIG/llama-swap.yaml"
API_KEY_FILE="$ULA_CONFIG/api-key"

yaml_q() { printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"; }
json_q() { printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"; }

# Per-install API key: the router has no auth otherwise, and any web page in a browser on this
# machine could talk to 127.0.0.1 (CORS / DNS rebinding) and read prompts.
ula_api_key() {
  if [ ! -s "$API_KEY_FILE" ]; then
    mkdir -p "$ULA_CONFIG"
    ( umask 077; od -An -tx1 -N24 /dev/urandom | tr -d ' \n' > "$API_KEY_FILE" )
  fi
  cat "$API_KEY_FILE"
}

# Identity of a profile entry's server process (same model + ctx + extra args = same process).
entry_key() { echo "$1" | cut -d'|' -f2-4; }

render_swap_yaml() {
  local server key resident="" extra_llms="" rag="" e alias id ctx extra kind file args name owner
  server="$(LLAMA_SERVER_BIN)"; key="$(ula_api_key)"
  mkdir -p "$ULA_CONFIG"
  ( umask 077; : > "$SWAP_YAML.tmp" )
  {
    echo "# Generated by ula ($ULA_VERSION) for profile $ULA_PROFILE. Edit profiles/*.env; 'ula render' overwrites this."
    echo "healthCheckTimeout: 900"
    echo "logLevel: info"
    echo "logToStdout: \"proxy\""
    echo "startPort: 18100"
    echo "globalTTL: 0"
    echo "sendLoadingState: true"
    echo "captureBuffer: 0"
    echo "apiKeys:"
    echo "  - $(yaml_q "$key")"
    echo "security:"
    echo "  cors:"
    echo "    allowedOrigins:"
    echo "      - $(yaml_q "http://$ULA_HOST:$ULA_PORT")"
    echo "macros:"
    echo "  server: >-"
    echo "    \"$server\" --host 127.0.0.1 --port \${PORT} --api-key $key --jinja --flash-attn on --parallel 1 --no-webui"
    echo "models:"
    local seen_keys="" a
    for alias in $(profile_aliases); do
      e="$(entry_for_alias "$alias")"
      id="$(echo "$e" | cut -d'|' -f2)"; ctx="$(echo "$e" | cut -d'|' -f3)"; extra="$(echo "$e" | cut -d'|' -f4)"
      model_installed "$id" || continue
      # Identical entries (e.g. coder and architect on the same small model) share one process.
      case "$seen_keys" in *"[$(entry_key "$e")]"*) continue ;; esac
      seen_keys="${seen_keys}[$(entry_key "$e")]"
      kind="$(catalog_field "$id" 2)"; file="$(catalog_field "$id" 4)"; args="$(expand_args "$(catalog_field "$id" 8)")"
      name="${file%.gguf}"
      echo "  $(yaml_q "$alias"):"
      echo "    name: $(yaml_q "$name")"
      echo "    description: $(yaml_q "$id ($kind, ctx $ctx)")"
      local aliases=""
      for a in $(profile_aliases); do
        [ "$a" = "$alias" ] && continue
        [ "$(entry_key "$(entry_for_alias "$a")")" = "$(entry_key "$e")" ] && aliases="$aliases $a"
      done
      if [ -n "$aliases" ]; then
        echo "    aliases:"; for a in $aliases; do echo "      - $(yaml_q "$a")"; done
      fi
      echo "    cmd: |"
      echo "      \${server}"
      echo "      --model \"$ULA_MODELS_DIR/$file\""
      echo "      --ctx-size $ctx"
      [ -n "$ULA_GPU_ARGS" ] && echo "      $ULA_GPU_ARGS"
      [ "$kind" = chat ] && [ -n "${ULA_CHAT_ARGS:-}" ] && echo "      $ULA_CHAT_ARGS"
      [ -n "$args" ] && echo "      $args"
      [ -n "$extra" ] && echo "      $extra"
      if [ -n "${ULA_SERVER_ENV:-}" ]; then
        echo "    env:"
        for kv in $ULA_SERVER_ENV; do echo "      - $(yaml_q "$kv")"; done
      fi
      if [ "$kind" = chat ]; then
        echo "    ttl: $ULA_TTL"
        echo "    filters:"
        echo "      setParamsByID:"
        for a in "$alias" $aliases; do
          echo "        $(yaml_q "$a:fast"):"
          echo "          chat_template_kwargs:"
          echo "            enable_thinking: false"
          echo "            reasoning_effort: \"low\""
        done
        case " $ULA_CODER $ULA_ARCHITECT " in
          *" $alias "*) resident="$resident $alias" ;;
          *) extra_llms="$extra_llms $alias" ;;
        esac
      else
        echo "    ttl: 0"
        rag="$rag $alias"
      fi
    done
    echo "routing:"
    echo "  router:"
    echo "    use: group"
    echo "    settings:"
    echo "      groups:"
    if [ "$ULA_SWAP_LLMS" = true ]; then
      # one chat model at a time, whichever alias is asked for
      resident="$resident $extra_llms"; extra_llms=""
    fi
    if [ -n "${resident// /}" ]; then
      echo "        main:"
      echo "          swap: $ULA_SWAP_LLMS"
      echo "          exclusive: $([ -n "${extra_llms// /}" ] && echo true || echo false)"
      echo "          members:"
      for a in $resident; do echo "            - $(yaml_q "$a")"; done
    fi
    if [ -n "${extra_llms// /}" ]; then
      # stock / alternative models on big machines: loaded alone, unloading the resident pair
      echo "        extra:"
      echo "          swap: true"
      echo "          exclusive: true"
      echo "          members:"
      for a in $extra_llms; do echo "            - $(yaml_q "$a")"; done
    fi
    if [ -n "${rag// /}" ]; then
      echo "        rag:"
      echo "          swap: false"
      echo "          exclusive: false"
      echo "          persistent: true"
      echo "          members:"
      for a in $rag; do echo "            - $(yaml_q "$a")"; done
    fi
  } >> "$SWAP_YAML.tmp"
  [ -n "${resident// /}" ] || warn "no chat model is installed yet; run 'ula pull'"
  mv "$SWAP_YAML.tmp" "$SWAP_YAML"
  info "wrote $SWAP_YAML"
  # llama-swap polls the file every 2 s (--watch-config); let it reload before anyone sends requests.
  if curl -fsS --max-time 2 "http://$ULA_HOST:$ULA_PORT/health" >/dev/null 2>&1; then sleep 4; fi
}

# The alias an agent should use: itself if downloaded, else the coder.
effective_alias() {
  local e; e="$(entry_for_alias "$1")"
  if [ -n "$e" ] && model_installed "$(echo "$e" | cut -d'|' -f2)"; then echo "$1"; else echo "$ULA_CODER"; fi
}

# Copy a template file, backing up a same-named file that ula did not write.
install_managed() { # src dst
  local src="$1" dst="$2"
  if [ -f "$dst" ] && ! grep -q 'managed-by: ula' "$dst"; then
    cp -p "$dst" "$dst.bak.$(date +%Y%m%d%H%M%S)"; warn "existing $dst backed up to $dst.bak.*"
  fi
  sed "s|@ARCHITECT@|ula/$ARCH_EFF|g; s|@CODER@|ula/$ULA_CODER|g" "$src" > "$dst"
}

# Writes ~/.config/opencode/opencode.jsonc (backing up a foreign one), agents and instructions.
render_opencode() {
  local cfg="$OPENCODE_CFG_DIR/opencode.jsonc" alias e id ctx kind out first=1 models="" f
  mkdir -p "$OPENCODE_CFG_DIR/agents"
  for f in "$OPENCODE_CFG_DIR/opencode.jsonc" "$OPENCODE_CFG_DIR/opencode.json"; do
    if [ -f "$f" ] && ! grep -q 'managed-by: ula' "$f"; then
      cp -p "$f" "$f.bak.$(date +%Y%m%d%H%M%S)"
      warn "existing $f backed up to $f.bak.*"
      [ "$f" = "$OPENCODE_CFG_DIR/opencode.json" ] && rm -f "$f"
    fi
  done
  ARCH_EFF="$(effective_alias "$ULA_ARCHITECT")"
  [ "$ARCH_EFF" = "$ULA_ARCHITECT" ] || warn "$ULA_ARCHITECT is not downloaded; plan/architect/reviewer agents use $ULA_CODER"
  for alias in $(profile_aliases); do
    e="$(entry_for_alias "$alias")"; id="$(echo "$e" | cut -d'|' -f2)"; ctx="$(echo "$e" | cut -d'|' -f3)"
    model_installed "$id" || continue
    kind="$(catalog_field "$id" 2)"; [ "$kind" = chat ] || continue
    out=$(( ctx / 4 )); [ "$out" -gt 16384 ] && out=16384
    [ $first = 1 ] || models="$models,"
    first=0
    models="$models
        $(json_q "$alias"): {
          \"modelID\": $(json_q "$alias"),
          \"name\": $(json_q "$alias · $(catalog_field "$id" 4 | sed 's/\.gguf$//')"),
          \"capabilities\": { \"tools\": true, \"temperature\": true, \"reasoning\": { \"supported\": true }, \"input\": [\"text\"], \"output\": [\"text\"] },
          \"limit\": { \"context\": $ctx, \"output\": $out }
        }"
  done
  local plugins="[]" websearch="deny"
  [ "${ULA_SUPERPOWERS:-1}" = 1 ] && [ -f "$(SUPERPOWERS_DIR)/index.js" ] && plugins="[$(json_q "$(SUPERPOWERS_DIR)")]"
  [ "${ULA_WEBSEARCH:-0}" = 1 ] && websearch="ask"
  ( umask 077; : > "$cfg.tmp" )
  cat >> "$cfg.tmp" <<EOF
// managed-by: ula — regenerated by 'ula render'. Project opencode.jsonc / .opencode/ are ignored
// unless ULA_PROJECT_CONFIG=1 (they could override providers and permissions).
{
  "\$schema": "https://opencode.ai/config.json",
  "model": "ula/$ULA_CODER",
  "default_agent": "build",
  "share": "disabled",
  "update": "disable",
  "instructions": [$(json_q "$OPENCODE_CFG_DIR/ula-instructions.md")],
  "plugins": $plugins,
  "providers": {
    "ula": {
      "name": "Local (llama-swap)",
      "package": "@opencode/ai/providers/openai-compatible",
      "settings": {
        "baseURL": "http://$ULA_HOST:$ULA_PORT/v1",
        "apiKey": $(json_q "$(ula_api_key)"),
        "timeout": false,
        "headerTimeout": 1800000,
        "chunkTimeout": 900000
      },
      "compatibility": { "reasoningField": "reasoning_content", "maxTokensField": "max_tokens" },
      "models": {$models
      }
    }
  },
  // Only the local provider may be used; no cloud search integration.
  "policies": [
    { "action": "provider.use", "resource": "*", "effect": "deny" },
    { "action": "provider.use", "resource": "ula", "effect": "allow" },
    { "action": "integration.use", "resource": "exa", "effect": "deny" }
  ],
  "agents": {
    "build":   { "model": "ula/$ULA_CODER" },
    "plan":    { "model": "ula/$ARCH_EFF" },
    "general": { "model": "ula/$ULA_CODER" },
    "explore": {
      "model": "ula/$ULA_CODER",
      "permissions": [
        { "action": "shell", "resource": "*", "effect": "ask" },
        { "action": "shell", "resource": "rg *", "effect": "allow" },
        { "action": "shell", "resource": "grep *", "effect": "allow" },
        { "action": "shell", "resource": "ls *", "effect": "allow" },
        { "action": "shell", "resource": "git log *", "effect": "allow" },
        { "action": "shell", "resource": "git diff *", "effect": "allow" },
        { "action": "shell", "resource": "git show *", "effect": "allow" },
        { "action": "shell", "resource": "git status *", "effect": "allow" },
        { "action": "webfetch", "resource": "*", "effect": "ask" },
        { "action": "external_directory", "resource": "*", "effect": "ask" }
      ]
    }
  },
  "permissions": [
    { "action": "shell", "resource": "git push *", "effect": "ask" },
    { "action": "shell", "resource": "sudo *", "effect": "ask" },
    { "action": "websearch", "resource": "*", "effect": "$websearch" }
  ]
}
EOF
  mv "$cfg.tmp" "$cfg"
  install_managed "$ULA_ROOT/templates/opencode/instructions.md" "$OPENCODE_CFG_DIR/ula-instructions.md"
  for f in "$ULA_ROOT"/templates/opencode/agents/*.md; do
    install_managed "$f" "$OPENCODE_CFG_DIR/agents/$(basename "$f")"
  done
  info "wrote $cfg (+ agents/, ula-instructions.md)"
}
